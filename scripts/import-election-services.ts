// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

interface ElectionServiceDefinition {
  /** Two-letter postal abbreviation, used only for logging. */
  abbr: string;
  /** Must match jurisdictions.slug in the database. */
  jurisdictionSlug: string;
  election_office_name: string;
  registration_url: string;
  /** URL to check existing voter registration status (may be same as registration_url). */
  registration_status_url: string | null;
  has_online_registration: boolean;
  ballot_tracking_url: string | null;
  has_ballot_tracking: boolean;
  election_office_phone: string | null;
  election_office_email: string | null;
  election_office_address: string | null;
  /** Free-form notes on registration requirements. */
  requirements: string | null;
}

