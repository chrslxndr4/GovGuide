async function importElectionServices(): Promise<void> {
  console.log('=== Import Election Services ===\n');
  console.log(`Processing ${ELECTION_SERVICES.length} state/jurisdiction records …\n`);

  let inserted = 0;
  let skipped = 0;

  for (const def of ELECTION_SERVICES) {
    process.stdout.write(`  ${def.abbr} — ${def.election_office_name} … `);

    // Resolve jurisdiction_id from the slug.
    const { data: jurisdiction, error: jErr } = await supabase
      .from('jurisdictions')
      .select('id')
      .eq('slug', def.jurisdictionSlug)
      .maybeSingle();

    if (jErr) {
      console.error(`ERROR (db): ${jErr.message}`);
      skipped++;
      continue;
    }

    if (!jurisdiction) {
      console.warn(`SKIP — jurisdiction not found (slug="${def.jurisdictionSlug}")`);
      skipped++;
      continue;
    }

    const record: ElectionServiceInsert = {
      jurisdiction_id: (jurisdiction as { id: string }).id,
      election_office_name: def.election_office_name,
      registration_url: def.registration_url,
      registration_status_url: def.registration_status_url,
      has_online_registration: def.has_online_registration,
      ballot_tracking_url: def.ballot_tracking_url,
      has_ballot_tracking: def.has_ballot_tracking,
      election_office_phone: def.election_office_phone,
      election_office_email: def.election_office_email,
      election_office_address: def.election_office_address,
      requirements: def.requirements,
    };

    const { error } = await supabase
      .from('election_services')
      .upsert(record, { onConflict: 'jurisdiction_id' });

    if (error) {
      console.error(`ERROR: ${error.message}`);
      skipped++;
    } else {
      console.log('OK');
      inserted++;
    }
  }

  console.log(
    `\n=== Completed. Inserted/updated: ${inserted}, skipped: ${skipped} ===`,
  );
}

importElectionServices().catch((err) => {
  console.error('\nFatal error:', err);
  process.exit(1);
});
